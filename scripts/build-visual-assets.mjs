import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = process.cwd()
const selectionPath = resolve(root, 'design-system/visual-assets/icon-selection.json')
const lineMdSelectionPath = resolve(root, 'design-system/visual-assets/line-md-selection.json')
const outputPath = resolve(root, 'src/visual-assets/generated-icons.ts')
const lineMdOutputPath = resolve(root, 'src/visual-assets/generated-line-md-icons.ts')
const selection = JSON.parse(await readFile(selectionPath, 'utf8'))
const lineMdSelection = JSON.parse(await readFile(lineMdSelectionPath, 'utf8'))
const packageJson = JSON.parse(await readFile(resolve(root, 'node_modules/lucide-static/package.json'), 'utf8'))

if (selection.source !== 'lucide-static') throw new Error(`Unsupported static icon source: ${selection.source}`)
if (packageJson.version !== selection.version) throw new Error(`Lucide version mismatch: expected ${selection.version}, found ${packageJson.version}`)

const selected = []
const seen = new Set()

for (const group of selection.groups) {
  for (const name of group.icons) {
    if (seen.has(name)) continue
    const source = await readFile(resolve(root, `node_modules/lucide-static/icons/${name}.svg`), 'utf8').catch(() => '')
    if (!source) throw new Error(`Unknown Lucide icon: ${name}`)
    assertSafeSvg(source, name)
    const viewBox = /\bviewBox="([^"]+)"/.exec(source)?.[1]
    const body = /<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/.exec(source)?.[1]
    if (!viewBox || body === undefined) throw new Error(`Malformed SVG: ${name}`)
    selected.push({
      name,
      label: name.split('-').map(word => word ? word[0].toUpperCase() + word.slice(1) : '').join(' '),
      group: group.id,
      groupLabel: group.label,
      aliases: [...new Set([...group.aliases, ...name.split('-')])],
      viewBox,
      // Lucide defines its visual language on the root <svg>. Preserve that
      // contract after extracting the geometry so paths do not fall back to
      // filled SVG defaults in the shared renderer.
      body: `<g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body.trim()}</g>`,
    })
    seen.add(name)
  }
}

if (selected.length < 150) throw new Error(`Production selection requires at least 150 unique icons, found ${selected.length}`)

const source = `// Generated by scripts/build-visual-assets.mjs from lucide-static@${selection.version}. Do not edit.\n` +
  `export const generatedLucideIcons = ${JSON.stringify(selected, null, 2)} as const\n`
await writeFile(outputPath, source)

const lineMdPackage = JSON.parse(await readFile(resolve(root, 'node_modules/@iconify-json/line-md/package.json'), 'utf8'))
const lineMdCollection = JSON.parse(await readFile(resolve(root, 'node_modules/@iconify-json/line-md/icons.json'), 'utf8'))
if (lineMdPackage.version !== lineMdSelection.version) throw new Error(`Line MD version mismatch: expected ${lineMdSelection.version}, found ${lineMdPackage.version}`)
if (lineMdSelection.production.length !== 48 || new Set(lineMdSelection.production).size !== 48) throw new Error('Line MD production allowlist must contain 48 unique names')
if (lineMdSelection.heroQualified.length !== 12 || lineMdSelection.heroQualified.some(name => !lineMdSelection.production.includes(name))) throw new Error('Line MD hero-qualified set must contain 12 production names')
const lineMdIcons = lineMdSelection.production.map(name => {
  const icon = lineMdCollection.icons[name]
  if (!icon) throw new Error(`Unknown Line MD icon: ${name}`)
  if (/(?:filled|twotone|off|transition)/.test(name)) throw new Error(`Line MD production icon must use the restrained outline family: ${name}`)
  assertSafeSvg(icon.body, `line-md:${name}`)
  const animated = /<(?:animate|animateTransform|set)\b/i.test(icon.body)
  const loop = /repeatCount="indefinite"/i.test(icon.body)
  const namespacedBody = namespaceSvgIds(icon.body, `line-md-${name}`)
  const body = animated ? applyMaterialMotionCurves(namespacedBody, loop) : namespacedBody
  return {
    name,
    label: name.split('-').map(word => word ? word[0].toUpperCase() + word.slice(1) : '').join(' '),
    aliases: [...new Set(name.split('-').filter(Boolean))],
    viewBox: `0 0 ${icon.width ?? lineMdCollection.width ?? 24} ${icon.height ?? lineMdCollection.height ?? 24}`,
    body,
    animated,
    mode: loop ? 'loop' : animated ? 'enter' : 'none',
    posterTimeMs: loop ? 1500 : 1200,
    qualityTier: lineMdSelection.heroQualified.includes(name) ? 'hero' : 'production',
  }
})
const lineMdSource = `// Generated by scripts/build-visual-assets.mjs from @iconify-json/line-md@${lineMdPackage.version}. Do not edit.\n` +
  `export const generatedLineMdIcons = ${JSON.stringify(lineMdIcons)} as const\n`
await writeFile(lineMdOutputPath, lineMdSource)

function assertSafeSvg(svg, name) {
  const forbidden = [/<script\b/i, /\son[a-z]+\s*=/i, /<foreignObject\b/i, /<(?:image|iframe|audio|video)\b/i, /\b(?:href|src)\s*=\s*["'](?:https?:|\/\/|data:)/i]
  const violation = forbidden.find(pattern => pattern.test(svg))
  if (violation) throw new Error(`Unsafe SVG ${name}: ${violation}`)
}

function applyMaterialMotionCurves(body, loop) {
  return body.replace(/<(animateTransform|animate)\b([^>]*)>/g, (tag, element, attributes) => {
    if (/\bcalcMode=/.test(attributes) || !/\bdur=/.test(attributes)) return tag
    const selfClosing = /\/\s*$/.test(attributes)
    const cleanAttributes = attributes.replace(/\/\s*$/, '')
    const values = /\bvalues="([^"]+)"/.exec(cleanAttributes)?.[1].split(';').filter(Boolean)
    const keyTimes = /\bkeyTimes="([^"]+)"/.exec(cleanAttributes)?.[1].split(';').filter(Boolean)
    const segments = Math.max(1, (values?.length ?? keyTimes?.length ?? 2) - 1)
    const attribute = /\battributeName="([^"]+)"/.exec(cleanAttributes)?.[1]
    const indefinite = /\brepeatCount="indefinite"/.test(cleanAttributes)
    const continuous = loop && indefinite && !keyTimes && (values?.length ?? 2) <= 2
    if (continuous) return `<${element}${cleanAttributes} calcMode="linear"${selfClosing ? '/' : ''}>`
    const curve = indefinite || element === 'animateTransform' || attribute === 'd'
      ? '0.2 0 0 1'
      : '0.05 0.7 0.1 1'
    return `<${element}${cleanAttributes} calcMode="spline" keySplines="${Array.from({ length: segments }, () => curve).join(';')}"${selfClosing ? '/' : ''}>`
  })
}

function namespaceSvgIds(body, prefix) {
  const ids = [...body.matchAll(/\bid="([^"]+)"/g)].map(match => match[1])
  let result = body
  for (const id of ids) {
    const next = `${prefix}-${id}`
    result = result.replaceAll(`id="${id}"`, `id="${next}"`)
    result = result.replaceAll(`url(#${id})`, `url(#${next})`)
    result = result.replaceAll(`href="#${id}"`, `href="#${next}"`)
  }
  return result
}

process.stdout.write(`Generated ${selected.length} Lucide icons and ${lineMdIcons.length} Line MD icons\n`)
